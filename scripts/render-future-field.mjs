import { writeFileSync } from 'node:fs';
import { advanceField, createFieldParticles, FIELD_HEIGHT, FIELD_WIDTH } from '../src/futureFieldMotion.ts';

// Keep the no-canvas / Reduce Motion artwork at the same dimensions and dot scale.
const dots = createFieldParticles();
advanceField(dots, 0, 0, { x: 0, y: 0, strength: 0 });
const circles = dots.filter(dot => dot.alpha >= .001).map(dot =>
  `  <circle cx="${dot.x.toFixed(3)}" cy="${dot.y.toFixed(3)}" r="${dot.radius}" fill="${dot.color}" opacity="${dot.alpha.toFixed(4)}" />`,
);
writeFileSync(new URL('../public/assets/future-field.svg', import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg" width="${FIELD_WIDTH}" height="${FIELD_HEIGHT}" viewBox="0 0 ${FIELD_WIDTH} ${FIELD_HEIGHT}" fill="none">\n<!-- Generated by scripts/render-future-field.mjs. -->\n${circles.join('\n')}\n</svg>\n`);
console.log(`Rendered ${circles.length} visible dots in the ${FIELD_WIDTH} x ${FIELD_HEIGHT} still fallback.`);
